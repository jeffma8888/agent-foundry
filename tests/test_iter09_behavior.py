# --- Behavior 1 -- non-empty, deterministic (pure), never raises -----------
def test_b01_nonempty_deterministic_pure():
    for text in ("", _learnings_text(4, "p1", "p2")):
        a = foundry.render_agents_md(text, "ProdName-Alpha")   # must not raise
        b = foundry.render_agents_md(text, "ProdName-Alpha")   # identical args
        assert isinstance(a, str) and a != "", "render_agents_md returned empty/non-str"
        assert a == b, "render_agents_md is not deterministic for identical args"
        # byte-identical, per the spec's purity requirement
        assert a.encode("utf-8") == b.encode("utf-8")


# --- Behavior 2 -- top heading names the product ---------------------------
def test_b02_top_heading_names_product():
    name = "MyCoolProduct-XYZ"
    out = foundry.render_agents_md(_learnings_text(3), name)
    first = _first_nonempty_line(out)
    assert first.startswith("# "), f"first non-empty line is not a top-level `# ` heading: {first!r}"
    assert name in first, f"product name {name!r} not present verbatim in the top heading: {first!r}"


# --- Behavior 3 -- auto-generated banner with the 3 literal substrings ------
def test_b03_autogenerated_banner_substrings():
    # learnings text I control contains NONE of the banner literals, so the
    # "banner sits above the learnings content" ordering check is meaningful.
    text = _learnings_text(3, "just a plain rule")
    out = foundry.render_agents_md(text, "BannerProd")
    for lit in ("auto-generated", "foundry agents", "LEARNINGS.md"):
        assert lit in out, f"banner literal {lit!r} missing from render output"
    # banner is ABOVE the embedded learnings content (digest)
    digest = foundry.learnings_digest(text, recent=12)
    assert out.find("auto-generated") < out.find(digest), "banner does not precede the learnings digest"


# --- Behavior 4 -- embeds the bounded learnings digest VERBATIM -------------
def test_b04_embeds_digest_verbatim():
    text = _learnings_text(6, "pattern alpha", "pattern beta")
    for recent in (4, 12):
        out = foundry.render_agents_md(text, "EmbedProd", recent=recent)
        expected = foundry.learnings_digest(text, recent=recent)
        assert expected in out, (
            f"learnings_digest(text, recent={recent}) is not a contiguous substring "
            "of render_agents_md output (digest not embedded verbatim)"
        )


# --- Behavior 5 -- `recent` bounds the embedded lessons + accurate header ---
def test_b05_recent_bounds_lessons_and_header():
    M = 5
    text = _learnings_text(M, "a rule")   # ids 1..5
    for recent in (0, 3, 5, 12):
        out = foundry.render_agents_md(text, "BoundProd", recent=recent)
        k = min(recent, M)
        # count of `- [` lesson lines in the WHOLE returned string == min(recent, M)
        assert _count_lesson_lines(out) == k, (
            f"recent={recent}: expected {k} lesson lines, got {_count_lesson_lines(out)}"
        )
        # header reports K == min(recent, M) and the true M
        assert f"## Recent lessons (last {k} of {M})" in out, (
            f"recent={recent}: header '## Recent lessons (last {k} of {M})' not found"
        )
    # recent == 0 -> exactly zero, no negative-slice wrap-around
    out0 = foundry.render_agents_md(text, "BoundProd", recent=0)
    assert _count_lesson_lines(out0) == 0
    for i in range(1, M + 1):
        assert _marker(i) not in out0, "recent=0 leaked a lesson (negative-slice wrap-around?)"


# --- Behavior 6 -- empty learnings -> stable placeholder --------------------
def test_b06_empty_learnings_stable_placeholder():
    out = foundry.render_agents_md("", "EmptyProd")
    # still satisfies Behaviors 1-3
    assert isinstance(out, str) and out != ""
    first = _first_nonempty_line(out)
    assert first.startswith("# ") and "EmptyProd" in first
    for lit in ("auto-generated", "foundry agents", "LEARNINGS.md"):
        assert lit in out
    # embeds the placeholder digest (== learnings_digest("", recent=12))
    placeholder = foundry.learnings_digest("", recent=12)
    assert placeholder in out, "empty-text placeholder digest not embedded"
    assert "## Recent lessons (last 0 of 0)" in out
    assert _count_lesson_lines(out) == 0


