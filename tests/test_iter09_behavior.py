"""Black-box behaviour tests for iter 09 -- the `render_agents_md` helper +
the on-demand `foundry agents` CLI subcommand (emit an AGENTS.md house-rules
file into a product repo from its learnings).

ISOLATION: written from the PM spec (Expected Behaviors 1-12) and the product's
own observable behavior only. The implementation source (foundry.py internals),
the engineer/reviewer notes, and `git diff` were NOT read. Every check drives
the public interface: the pure helper `foundry.render_agents_md(text, name,
recent=...)` against synthetic input strings, and the CLI via
`foundry.main(["agents", ...])` with a temp config whose `repo` field is a tmp
dir (the real foundry repo is NEVER touched). Expected content is computed via
the public pure helpers `foundry.render_agents_md(...)` / `foundry.learnings_digest(...)`.
Fully offline and deterministic -- real temp files only, NO subprocess/git/network/
agent-run except the `--help` regression probe (which only prints usage and exits).
"""
import json
import pathlib
import sys

import pytest

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import foundry  # noqa: E402
import dispatcher  # noqa: E402


# --------------------------------------------------------------------------
# helpers (mirror the suite's conventions; repo defaults to a TMP dir so the
# `agents` command can never write into the real foundry repo -- Behavior 11)
# --------------------------------------------------------------------------
def _write_cfg(tmp_path, **over):
    data = {
        "name": "demoprod",
        "repo": str(tmp_path / "repo"),          # TMP repo -> real repo untouched
        "allowed_push_repo": "demoprod",
        "vision": str(tmp_path / "VISION.md"),
        "work_root": str(tmp_path / "work"),
    }
    data.update(over)
    p = tmp_path / "config.json"
    p.write_text(json.dumps(data))
    return p


def _cfg_with_learnings(tmp_path, file_text, **over):
    """Load a config + seed <work_root>/LEARNINGS.md (cfg.learnings) with text."""
    cfg = foundry.load_config(str(_write_cfg(tmp_path, **over)))
    lp = pathlib.Path(cfg.learnings)
    lp.parent.mkdir(parents=True, exist_ok=True)
    lp.write_text(file_text)
    return cfg


def _marker(i):
    return f"UNIQMARK-{i:03d}"


def _lesson(i, tag="ENG"):
    """A role-tagged lesson line: `- [ENG iterNN] <unique marker> ...`."""
    return f"- [{tag} iter{i:02d}] {_marker(i)} some durable detail text here"


def _patterns_head(*bullets):
    """A `## Patterns` head: heading + blurb + plain `- ` pattern bullets."""
    lines = ["## Patterns", "", "Read this head first; the tail is the history.", ""]
    lines += [f"- {b}" for b in bullets]
    return "\n".join(lines)


def _learnings_text(n_lessons, *patterns):
    """A realistic LEARNINGS.md: patterns head + chronological lessons tail."""
    head = _patterns_head(*patterns) if patterns else _patterns_head("a durable rule")
    tail = "\n".join(_lesson(i) for i in range(1, n_lessons + 1))
    return head + "\n\n## Chronological lessons\n\n" + tail + "\n"


def _count_lesson_lines(text):
    """Count lines whose left-stripped form starts with the 3 chars '- ['."""
    return sum(1 for ln in text.splitlines() if ln.lstrip().startswith("- ["))


def _first_nonempty_line(text):
    for ln in text.splitlines():
        if ln.strip():
            return ln
    return ""


