# --- Behavior 7 -- default WRITES the repo's AGENTS.md ---------------------
def test_b07_default_writes_repo_agents_md(tmp_path, capsys):
    text = _learnings_text(6, "cli pat one", "cli pat two")
    cfg = _cfg_with_learnings(tmp_path, text)
    cfg_path = tmp_path / "config.json"
    agents_md = pathlib.Path(cfg.repo) / "AGENTS.md"
    assert not agents_md.exists(), "precondition: AGENTS.md must not exist yet"

    rc = foundry.main(["agents", "--config", str(cfg_path)])
    capsys.readouterr()
    assert rc == 0, f"agents returned {rc!r}, expected 0"
    assert agents_md.exists(), "default agents did not write <cfg.repo>/AGENTS.md"
    # exact contents == render_agents_md(<learnings-text>, cfg.name, recent=12)
    expected = foundry.render_agents_md(text, cfg.name, recent=12)
    assert agents_md.read_text() == expected, "written AGENTS.md != render_agents_md(text, name, 12)"


# --- Behavior 8 -- `--print` prints and writes NOTHING ---------------------
def test_b08_print_prints_writes_nothing(tmp_path, capsys):
    text = _learnings_text(5, "print pat")
    cfg = _cfg_with_learnings(tmp_path, text)
    cfg_path = tmp_path / "config.json"
    agents_md = pathlib.Path(cfg.repo) / "AGENTS.md"
    assert not agents_md.exists(), "precondition: AGENTS.md must not exist yet"

    rc = foundry.main(["agents", "--config", str(cfg_path), "--print"])
    out = capsys.readouterr().out
    assert rc == 0, f"agents --print returned {rc!r}, expected 0"
    expected = foundry.render_agents_md(text, cfg.name, recent=12)
    assert expected in out, "--print did not write the rendered document to stdout"
    # writes NOTHING: the file that did not exist before still does not exist
    assert not agents_md.exists(), "--print created/modified <cfg.repo>/AGENTS.md (must not)"


# --- Behavior 9 -- `--recent N` bounds the output (default 12) --------------
def test_b09_recent_bounds_cli_output(tmp_path, capsys):
    text = _learnings_text(6, "pat")   # M = 6 lessons -> 3 != 12-bounded
    cfg = _cfg_with_learnings(tmp_path, text)
    cfg_path = tmp_path / "config.json"
    agents_md = pathlib.Path(cfg.repo) / "AGENTS.md"

    # --recent 3 -> content == render(..., recent=3), at most 3 `- [` lines
    rc = foundry.main(["agents", "--config", str(cfg_path), "--recent", "3"])
    capsys.readouterr()
    assert rc == 0
    written = agents_md.read_text()
    assert written == foundry.render_agents_md(text, cfg.name, recent=3)
    assert _count_lesson_lines(written) == 3, "at most 3 lesson lines expected with --recent 3"

    # default (no --recent) -> recent == 12 (keeps all 6, differs from recent=3)
    rc = foundry.main(["agents", "--config", str(cfg_path)])
    capsys.readouterr()
    assert rc == 0
    written_default = agents_md.read_text()
    assert written_default == foundry.render_agents_md(text, cfg.name, recent=12)
    assert written_default != foundry.render_agents_md(text, cfg.name, recent=3), (
        "default --recent must be 12, not 3"
    )
    assert _count_lesson_lines(written_default) == 6


# --- Behavior 10 -- missing LEARNINGS.md is tolerated ----------------------
def test_b10_missing_learnings_tolerated(tmp_path, capsys):
    cfg = foundry.load_config(str(_write_cfg(tmp_path)))
    cfg_path = tmp_path / "config.json"
    assert not pathlib.Path(cfg.learnings).exists(), "learnings file must be absent"
    agents_md = pathlib.Path(cfg.repo) / "AGENTS.md"

    rc = foundry.main(["agents", "--config", str(cfg_path)])   # must not raise
    capsys.readouterr()
    assert rc == 0, "agents must return 0 when LEARNINGS.md is absent"
    assert agents_md.exists(), "agents must still write a valid AGENTS.md"
    # built from the empty-text placeholder digest
    assert agents_md.read_text() == foundry.render_agents_md("", cfg.name, recent=12)
    assert "## Recent lessons (last 0 of 0)" in agents_md.read_text()


# --- Behavior 11 -- repo-agnostic target; parent dir auto-created ----------
def test_b11_repo_agnostic_target(tmp_path, capsys):
    # cfg.repo points at a NESTED path whose parent does not exist yet, proving
    # the command computes the target from `repo` only and mkdirs parents.
    nested_repo = tmp_path / "does" / "not" / "exist" / "repo"
    assert not nested_repo.exists()
    text = _learnings_text(2, "pat")
    cfg = _cfg_with_learnings(tmp_path, text, repo=str(nested_repo))
    cfg_path = tmp_path / "config.json"

    rc = foundry.main(["agents", "--config", str(cfg_path)])
    capsys.readouterr()
    assert rc == 0
    target = pathlib.Path(cfg.repo) / "AGENTS.md"
    assert target.exists(), "agents did not create <cfg.repo>/AGENTS.md at the config-derived path"
    assert target == nested_repo / "AGENTS.md", "written path is not <cfg.repo>/AGENTS.md"


